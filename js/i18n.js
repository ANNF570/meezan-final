/* ════════════════════════════════════════════════════════════
   APPLY LANGUAGE — call applyLanguage('ar') to switch
   ════════════════════════════════════════════════════════════ */
window.applyLanguage = function(code) {
  const dict = window.MEEZAN_TRANSLATIONS[code] || window.MEEZAN_TRANSLATIONS['en'];
  const RTL_LANGS = ['ar','ur','fa','he'];
  const isRTL = RTL_LANGS.includes(code);

  /* Apply text to all elements with data-i18n attribute */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });

  /* Also apply to placeholders */
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.placeholder = dict[key];
  });

  /* Set page title */
  const pageTitleKey = document.body.dataset.page;
  if (pageTitleKey && dict[pageTitleKey]) {
    document.title = 'Meezan — ' + dict[pageTitleKey];
  }

  /* RTL / LTR */
  document.documentElement.setAttribute('dir', isRTL ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', code);

  /* RTL-specific font for Arabic script languages */
  const arabicFont = isRTL ? "'Noto Naskh Arabic', serif" : "'Crimson Pro', serif";
  document.documentElement.style.setProperty('--body-font', arabicFont);

  /* Save to localStorage */
  localStorage.setItem('meezan-lang', code);
};

/* ════════════════════════════════════════════════════════════
   AUTO-APPLY on page load
   ════════════════════════════════════════════════════════════ */
(function() {
  const saved = localStorage.getItem('meezan-lang') || 'en';
  if (saved !== 'en') {
    // Small delay to let the DOM load first
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', () => applyLanguage(saved));
    } else {
      applyLanguage(saved);
    }
  }
})();
